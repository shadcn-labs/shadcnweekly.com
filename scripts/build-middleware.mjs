import { fileURLToPath } from "node:url";

import { build as esbuildBuild } from "esbuild";

const outfile = fileURLToPath(new URL("../middleware.js", import.meta.url));
const entry = fileURLToPath(new URL("../middleware.src.ts", import.meta.url));

await esbuildBuild({
  banner: {
    js: "// Generated by scripts/build-middleware.mjs from middleware.src.ts. Do not edit by hand.",
  },
  bundle: true,
  entryPoints: [entry],
  format: "esm",
  legalComments: "inline",
  logLevel: "warning",
  outfile,
  platform: "neutral",
  plugins: [
    {
      // @dualmark/vercel dynamically imports next/server for Next.js projects.
      // This is an Astro site, so stub it out: the import fails gracefully and
      // the middleware uses the plain-Response upstream.
      name: "stub-next-server",
      setup(esbuild) {
        // oxlint-disable-next-line require-unicode-regexp -- esbuild's Go regex engine does not support the u flag.
        esbuild.onResolve({ filter: /^next\/server$/ }, (args) => ({
          namespace: "next-server-stub",
          path: args.path,
        }));
        esbuild.onLoad(
          // oxlint-disable-next-line require-unicode-regexp -- esbuild's Go regex engine does not support the u flag.
          { filter: /.*/, namespace: "next-server-stub" },
          () => ({
            // Vercel's generic middleware uses x-middleware-next to continue
            // routing. This makes Dualmark's subrequest passthrough serve the
            // pre-built .md asset instead of an empty 200.
            contents:
              'export const NextResponse = { next: () => new Response(null, { headers: { "x-middleware-next": "1" } }) };',
            loader: "js",
          })
        );
      },
    },
  ],
  target: "es2022",
});

console.log("Built middleware.js");
